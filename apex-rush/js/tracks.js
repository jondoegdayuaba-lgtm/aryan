// The tracks. Each point is [x, z], [x, z, y] or [x, z, y, options]; the road
// is a smooth curve through them (y is height in metres). Options apply to the
// stretch from that point to the next one:
//   cp: true      a checkpoint gate at this point
//   walls: true   barriers on both sides
//   tunnel: true  a tunnel (includes walls)
//   gap: true     no road: a jump. Give the lip a `slope` so it launches you
//   slope: 0.2    force the road's gradient here (ramp lips and landings)
//   bank: 12      lean the road into the corner by this many degrees
//   w: 16         road width (default: the track's `width`)
//   boost: true   a boost pad here: it kicks you past top speed
//   launch: true  a jump pad here: it throws you into the air
//   hoop: true    on a jump's lip: a striped hoop over the gap
//   loop: 13      a loop of this radius starts here and ends at the next
//                 point, which should be about 20 m further on and 20 m to
//                 one side (see loops.js). Come in on a straight.
// Closed tracks start and finish on the same line and can have laps; open
// tracks run from the first point to the last.
// Medal times are in seconds; `npm run check:tracks` times a robot driver to
// help set them (gold is about what a bold robot manages).

